def row(label, r):
    c, s = r["client_ms"], r["server_ms"]
    return (f"| {label} | {r['throughput_rps']:.0f} | {c['p50']:.0f} | {c['p95']:.0f} | {c['p99']:.0f} | {c['max']:.0f} | "
            f"{s['p50']:.0f} / {s['p95']:.0f} | {r['errors']} / {r['requests']} |")


HDR = "| Configuration | Throughput (req/s) | p50 (ms) | p95 (ms) | p99 (ms) | max (ms) | Server-side p50 / p95 (ms) | Errors / requests |\n|---|---|---|---|---|---|---|---|"


def table(data, scen):
    return "\n".join([HDR] + [row(NAMES[k], data["runs"][k][scen]) for k in NAMES])


def ramp(data, key):
    rr = data["runs"][key]["ramp"]
    lines = ["| Concurrent users | Throughput (req/s) | p50 (ms) | p95 (ms) | p99 (ms) | Errors |", "|---|---|---|---|---|---|"]
    for u, r in rr.items():
        c = r["client_ms"]
        lines.append(f"| {u} | {r['throughput_rps']:.0f} | {c['p50']:.0f} | {c['p95']:.0f} | {c['p99']:.0f} | {r['errors']} |")
    return "\n".join(lines)


def cpu(data, key):
    c = data["runs"][key]["sustained_50"]["cpu"]
    return c


